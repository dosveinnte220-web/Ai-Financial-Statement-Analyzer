export function getSampleCsv(): string {
  const headers = [
    "period",
    "revenue",
    "cogs",
    "operatingIncome",
    "netIncome",
    "currentAssets",
    "currentLiabilities",
    "totalAssets",
    "totalLiabilities",
    "equity",
    "cash",
    "shortTermInvestments",
    "accountsReceivable",
    "operatingCashFlow",
    "capitalExpenditures",
    "debt",
    "depreciationAndAmortization",
  ];

  const rows = sampleFinancialPeriods.map((period) =>
    [
      period.period,
      period.revenue,
      period.cogs,
      period.operatingIncome,
      period.netIncome,
      period.currentAssets,
      period.currentLiabilities,
      period.totalAssets,
      period.totalLiabilities,
      period.equity,
      period.cash,
      period.shortTermInvestments,
      period.accountsReceivable,
      period.operatingCashFlow,
      period.capitalExpenditures,
      period.debt,
      period.depreciationAndAmortization,
    ].join(","),
  );

  return [headers.join(","), ...rows].join("\n");
}
